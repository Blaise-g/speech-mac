use std::{env, fs::File, io::{BufWriter, Write}, path::PathBuf};
const EXPECTED: (u8,u8,u8) = (17,0,0);
fn ranges(mut values: Vec<u32>) -> Vec<(u32,u32)> {
    values.sort_unstable(); values.dedup();
    let mut out=Vec::new();
    if values.is_empty(){return out;}
    let (mut start,mut end)=(values[0],values[0]);
    for value in values.into_iter().skip(1) { if value==end+1 {end=value;} else {out.push((start,end));start=value;end=value;} }
    out.push((start,end));out
}
fn emit_ranges(w:&mut BufWriter<File>,name:&str, values:Vec<u32>)->std::io::Result<()> {
    let rs=ranges(values);
    writeln!(w,"static const unsigned int phonon_{}_ranges[][2] = {{",name)?;
    for (a,b) in &rs {writeln!(w," {{0x{:X},0x{:X}}},",a,b)?;}
    writeln!(w,"}};\nstatic const unsigned int phonon_{}_ranges_count = sizeof(phonon_{}_ranges)/sizeof(phonon_{}_ranges[0]);",name,name,name)
}
fn main()->std::io::Result<()> {
    if std::char::UNICODE_VERSION != EXPECTED { panic!("expected Unicode 17.0.0 from pinned Rust 1.99.1, got {:?}",std::char::UNICODE_VERSION); }
    let out=env::args_os().nth(1).map(PathBuf::from).unwrap_or_else(||"src/phonon_prompt_unicode.inc".into());
    let mut w=BufWriter::new(File::create(out)?);
    writeln!(w,"/* Generated by pinned Rust 1.99.1, Unicode 17.0.0. */")?;
    writeln!(w,"typedef struct {{ unsigned int code; const unsigned char *bytes; unsigned char length; }} PhononUpperMap;\nstatic const PhononUpperMap phonon_upper_map[] = {{")?;
    for code in 0..=0x10ffff { if let Some(ch)=char::from_u32(code) { let mapped:String=ch.to_uppercase().collect(); if mapped!=ch.to_string() { let bytes=mapped.as_bytes(); write!(w," {{0x{:X}, (const unsigned char[]){{",code)?;for (i,b) in bytes.iter().enumerate(){if i>0{write!(w,",")?;}write!(w,"0x{:02X}",b)?;}writeln!(w,"}}, {} }},",bytes.len())?; } } }
    writeln!(w,"}};\nstatic const unsigned int phonon_upper_map_count = sizeof(phonon_upper_map)/sizeof(phonon_upper_map[0]);")?;
    let mut alnum=Vec::new();let mut space=Vec::new();
    for code in 0..=0x10ffff {if let Some(ch)=char::from_u32(code){if ch.is_alphanumeric(){alnum.push(code);}if ch.is_whitespace(){space.push(code);}}}
    emit_ranges(&mut w,"alnum",alnum)?;emit_ranges(&mut w,"space",space)?;w.flush()
}

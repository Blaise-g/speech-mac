#ifndef KOKORO_STREAM_BENCHMARK_H
#define KOKORO_STREAM_BENCHMARK_H

#include <stddef.h>

#define KOKORO_STREAM_SILENT_BINARY_MARKER "KOKORO_STREAM_MUTED_OUTPUT_V1"

/* Benchmark-only events; production builds compile these calls away. */
typedef enum {
    KOKORO_STREAM_BENCHMARK_SYNTHESIS_BEGIN,
    KOKORO_STREAM_BENCHMARK_SYNTHESIS_END,
    KOKORO_STREAM_BENCHMARK_CHUNK_BEGIN,
    KOKORO_STREAM_BENCHMARK_FIRST_CHUNK_READY,
    KOKORO_STREAM_BENCHMARK_BUFFER_ACCEPTED,
    KOKORO_STREAM_BENCHMARK_START_REQUESTED,
    KOKORO_STREAM_BENCHMARK_BUFFER_RECLAIMED,
    KOKORO_STREAM_BENCHMARK_BACKPRESSURE_BEGIN,
    KOKORO_STREAM_BENCHMARK_BACKPRESSURE_END,
    KOKORO_STREAM_BENCHMARK_AUDIOQUEUE_OPEN_BEGIN,
    KOKORO_STREAM_BENCHMARK_AUDIOQUEUE_OPEN_END,
    KOKORO_STREAM_BENCHMARK_AUDIOQUEUE_START_BEGIN,
    KOKORO_STREAM_BENCHMARK_DRAIN_COMPLETE,
    KOKORO_STREAM_BENCHMARK_QUEUE_STARVED,
    KOKORO_STREAM_BENCHMARK_EVENT_COUNT,
} KokoroStreamBenchmarkEvent;

void kokoro_stream_benchmark_event(KokoroStreamBenchmarkEvent event, size_t value);

#ifdef KOKORO_STREAM_BENCHMARK_TIMING
#define KOKORO_STREAM_BENCHMARK_RECORD(event, value) kokoro_stream_benchmark_event(event, value)
#else
#define KOKORO_STREAM_BENCHMARK_RECORD(event, value) ((void)0)
#endif

#endif

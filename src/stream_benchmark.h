#ifndef SPEECH_STREAM_BENCHMARK_H
#define SPEECH_STREAM_BENCHMARK_H

#include <stddef.h>

#define SPEECH_STREAM_SILENT_BINARY_MARKER "SPEECH_STREAM_MUTED_OUTPUT_V1"

/* Benchmark-only events; production builds compile these calls away. */
typedef enum {
    SPEECH_STREAM_BENCHMARK_SYNTHESIS_BEGIN,
    SPEECH_STREAM_BENCHMARK_SYNTHESIS_END,
    SPEECH_STREAM_BENCHMARK_CHUNK_BEGIN,
    SPEECH_STREAM_BENCHMARK_FIRST_CHUNK_READY,
    SPEECH_STREAM_BENCHMARK_BUFFER_ACCEPTED,
    SPEECH_STREAM_BENCHMARK_START_REQUESTED,
    SPEECH_STREAM_BENCHMARK_BUFFER_RECLAIMED,
    SPEECH_STREAM_BENCHMARK_BACKPRESSURE_BEGIN,
    SPEECH_STREAM_BENCHMARK_BACKPRESSURE_END,
    SPEECH_STREAM_BENCHMARK_AUDIOQUEUE_OPEN_BEGIN,
    SPEECH_STREAM_BENCHMARK_AUDIOQUEUE_OPEN_END,
    SPEECH_STREAM_BENCHMARK_AUDIOQUEUE_START_BEGIN,
    SPEECH_STREAM_BENCHMARK_DRAIN_COMPLETE,
    SPEECH_STREAM_BENCHMARK_QUEUE_STARVED,
    SPEECH_STREAM_BENCHMARK_EVENT_COUNT,
} SpeechStreamBenchmarkEvent;

void speech_stream_benchmark_event(SpeechStreamBenchmarkEvent event, size_t value);

#ifdef SPEECH_STREAM_BENCHMARK_TIMING
#define SPEECH_STREAM_BENCHMARK_RECORD(event, value) speech_stream_benchmark_event(event, value)
#else
#define SPEECH_STREAM_BENCHMARK_RECORD(event, value) ((void)0)
#endif

#endif
